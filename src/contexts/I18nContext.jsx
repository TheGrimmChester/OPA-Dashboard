const I18nContext = createContext({ locale: 'en', setLocale: () => {}, t: (k) => k })

export function I18nProvider({ children }) {
  const [locale, setLocale] = useState(() => localStorage.getItem('opa_locale') || 'en')
  const value = useMemo(() => {
    const dict = MESSAGES[locale] || MESSAGES.en
    return {
      locale,
      setLocale: (l) => {
        localStorage.setItem('opa_locale', l)
        setLocale(l)
      },
      t: (key) => dict[key] || MESSAGES.en[key] || key,
      locales: Object.keys(MESSAGES),
    }
  }, [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

export function LocaleSwitcher() {
  const { locale, setLocale, locales, t } = useI18n()
  return (
    <label className="oui-text-muted" style={{ display: 'inline-flex', alignItems: 'center', gap: 6, fontSize: 12 }}>
      {t('nav.locale')}
      <select className="oui-input" value={locale} onChange={(e) => setLocale(e.target.value)} style={{ padding: '2px 6px' }}>
        {locales.map((l) => <option key={l} value={l}>{l}</option>)}
      </select>
    </label>
  )
}
